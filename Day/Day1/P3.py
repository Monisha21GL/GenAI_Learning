# virtual environments: A 'venv' is a directory tht contains--->
# 1.A Copy of the Python interpreter
# 2.A Copy of the pip package manager [has it's own 'pip' executable]
# 3.its own site-packages directory (where all the packages are installed)
# where python installs third party libraries
# 4. Activation scripts that modify PATH

# to create virtual environment: python -m venv .venv
# to activate virtual environment: .venv\Scripts\activate.bat
#deactivate virtual environment: deactivate

#pip installation (install dependencies/libraries): pip install package_name (syntax)